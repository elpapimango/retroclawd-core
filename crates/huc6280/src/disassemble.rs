/// Disassembles the instruction at `bytes[0..]` located at logical address `addr`; returns the text and its length.
#[must_use]
pub fn disassemble(bytes: &[u8], addr: u16) -> (String, usize) {
    let b = |i: usize| bytes.get(i).copied().unwrap_or(0);
    let w = |i: usize| u16::from(b(i)) | (u16::from(b(i + 1)) << 8);
    let op = b(0);
    if op & 0x0F == 0x07 || op & 0x0F == 0x0F {
        let bit = (op >> 4) & 7;
        let (name, rel) = match (op & 0x0F, op & 0x80 != 0) {
            (0x07, false) => ("RMB", false),
            (0x07, true) => ("SMB", false),
            (_, false) => ("BBR", true),
            (_, true) => ("BBS", true),
        };
        return if rel {
            let target = addr.wrapping_add(3).wrapping_add(b(2) as i8 as u16);
            (format!("{name}{bit} ${:02X},${target:04X}", b(1)), 3)
        } else {
            (format!("{name}{bit} ${:02X}", b(1)), 2)
        };
    }
    let (name, mode) = entry(op);
    match mode {
        'i' => (name.to_string(), 1),
        '#' => (format!("{name} #${:02X}", b(1)), 2),
        'z' => (format!("{name} ${:02X}", b(1)), 2),
        'Z' => (format!("{name} ${:02X},X", b(1)), 2),
        'y' => (format!("{name} ${:02X},Y", b(1)), 2),
        'a' => (format!("{name} ${:04X}", w(1)), 3),
        'A' => (format!("{name} ${:04X},X", w(1)), 3),
        'B' => (format!("{name} ${:04X},Y", w(1)), 3),
        '(' => (format!("{name} (${:02X},X)", b(1)), 2),
        ')' => (format!("{name} (${:02X}),Y", b(1)), 2),
        'n' => (format!("{name} (${:02X})", b(1)), 2),
        'J' => (format!("{name} (${:04X})", w(1)), 3),
        'K' => (format!("{name} (${:04X},X)", w(1)), 3),
        'r' => {
            let target = addr.wrapping_add(2).wrapping_add(b(1) as i8 as u16);
            (format!("{name} ${target:04X}"), 2)
        }
        't' => (format!("{name} #${:02X},${:02X}", b(1), b(2)), 3),
        'u' => (format!("{name} #${:02X},${:02X},X", b(1), b(2)), 3),
        'T' => (format!("{name} #${:02X},${:04X}", b(1), w(2)), 4),
        'U' => (format!("{name} #${:02X},${:04X},X", b(1), w(2)), 4),
        _ => (
            format!("{name} ${:04X},${:04X},${:04X}", w(1), w(3), w(5)),
            7,
        ),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_few_instructions() {
        assert_eq!(disassemble(&[0xA9, 0x42], 0).0, "LDA #$42");
        assert_eq!(disassemble(&[0x53, 0x04], 0).0, "TAM #$04");
        assert_eq!(
            disassemble(&[0x73, 1, 2, 3, 4, 5, 6], 0),
            ("TII $0201,$0403,$0605".to_string(), 7)
        );
        assert_eq!(
            disassemble(&[0x8F, 0x20, 0xFE], 0x100),
            ("BBS0 $20,$0101".to_string(), 3)
        );
    }
}
